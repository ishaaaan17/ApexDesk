//! High-Throughput Virtual Matching Engine for ApexDesk.
//! Crosses incoming Market and Limit orders against resting liquidity in the L2 Order Book.
//! Supports:
//! - Multi-level book sweeping across price-time queues
//! - Partial and full execution fills
//! - Market order simulated slippage (configurable in Basis Points)
//! - Residual limit order posting to book
//! - Full integration with Order OMS state machine

use std::collections::HashMap;

use crate::models::account::UserId;
use crate::models::order::{Order, OrderId, OrderSide, OrderStatus, OrderType};
use crate::orderbook::OrderBook;
use crate::types::math::{normalize_to_tick, BasisPoints, NSE_DEFAULT_TICK_SIZE_PAISE};
use crate::types::Money;

/// Details of an individual trade execution fill generated by the matching engine.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExecutionFill {
    pub fill_id: u64,
    pub symbol: String,
    pub maker_order_id: OrderId,
    pub maker_user_id: UserId,
    pub taker_order_id: OrderId,
    pub taker_user_id: UserId,
    pub side: OrderSide,
    pub qty: u32,
    pub price: Money,
    pub timestamp_ns: u64,
}

/// The outcome of an order processed by the matching engine.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MatchResult {
    pub order_id: OrderId,
    pub status: OrderStatus,
    pub fills: Vec<ExecutionFill>,
    pub filled_qty: u32,
    pub remaining_qty: u32,
}

/// High-throughput matching engine holding active order books across traded symbols.
#[derive(Debug, Default)]
pub struct MatchingEngine {
    books: HashMap<String, OrderBook>,
    next_fill_id: u64,
    slippage_bps: u32,
}

impl MatchingEngine {
    /// Creates a new matching engine with 0 basis points slippage.
    pub fn new() -> Self {
        Self {
            books: HashMap::new(),
            next_fill_id: 1,
            slippage_bps: 0,
        }
    }

    /// Creates a new matching engine with simulated slippage (e.g., 3-5 BPS for Indian large-caps).
    pub fn with_slippage(slippage_bps: u32) -> Self {
        Self {
            books: HashMap::new(),
            next_fill_id: 1,
            slippage_bps,
        }
    }

    /// Returns a reference to the order book for the given symbol if it exists.
    pub fn get_book(&self, symbol: &str) -> Option<&OrderBook> {
        self.books.get(symbol)
    }

    /// Returns a mutable reference to the order book for the given symbol if it exists.
    pub fn get_book_mut(&mut self, symbol: &str) -> Option<&mut OrderBook> {
        self.books.get_mut(symbol)
    }

    /// Retrieves an existing order book or creates an empty one.
    pub fn get_or_create_book(&mut self, symbol: &str) -> &mut OrderBook {
        self.books
            .entry(symbol.to_string())
            .or_insert_with(|| OrderBook::new(symbol))
    }

    /// Processes an incoming order against the matching engine's internal order books.
    pub fn match_order(&mut self, order: &mut Order, timestamp_ns: u64) -> MatchResult {
        let symbol = order.symbol.clone();
        let book = self
            .books
            .entry(symbol)
            .or_insert_with(|| OrderBook::new(&order.symbol));

        Self::execute_matching(
            &mut self.next_fill_id,
            self.slippage_bps,
            order,
            book,
            timestamp_ns,
        )
    }

    /// Directly processes an incoming order against an external or provided order book.
    pub fn match_against_book(
        &mut self,
        order: &mut Order,
        book: &mut OrderBook,
        timestamp_ns: u64,
    ) -> MatchResult {
        Self::execute_matching(
            &mut self.next_fill_id,
            self.slippage_bps,
            order,
            book,
            timestamp_ns,
        )
    }

    /// Internal core execution logic: matches order against resting book.
    fn execute_matching(
        next_fill_id: &mut u64,
        slippage_bps: u32,
        order: &mut Order,
        book: &mut OrderBook,
        timestamp_ns: u64,
    ) -> MatchResult {
        // Ensure order is submitted
        if order.status == OrderStatus::Pending {
            let _ = order.submit();
        }

        let mut unfilled_qty = order.qty - order.filled_qty;
        let mut fills = Vec::new();

        let is_market = matches!(order.order_type, OrderType::Market);
        let limit_price = match &order.order_type {
            OrderType::Limit { limit_price } => Some(*limit_price),
            OrderType::Bracket {
                entry_limit: Some(limit),
                ..
            } => Some(*limit),
            _ => None,
        };

        match order.side {
            OrderSide::Buy => {
                // Taker is BUYER -> matches against ASKS (lowest price first)
                while unfilled_qty > 0 {
                    let lowest_ask_price = match book.asks_mut().keys().next().copied() {
                        Some(p) => p,
                        None => break, // Book exhausted
                    };

                    // Guard: If limit buy, stop if best ask exceeds limit price
                    if let Some(limit) = limit_price {
                        if lowest_ask_price > limit {
                            break;
                        }
                    }

                    // Match against front maker in queue at lowest ask price
                    let (is_queue_empty, fill) = {
                        let queue = book.asks_mut().get_mut(&lowest_ask_price).unwrap();
                        let maker = queue.front_mut().unwrap();
                        let match_qty = std::cmp::min(unfilled_qty, maker.qty);

                        // Calculate execution price with simulated slippage on market orders
                        let fill_price = if is_market && slippage_bps > 0 {
                            let slip_amount = BasisPoints(slippage_bps).apply_to(lowest_ask_price);
                            normalize_to_tick(
                                lowest_ask_price + slip_amount,
                                NSE_DEFAULT_TICK_SIZE_PAISE,
                            )
                        } else {
                            lowest_ask_price
                        };

                        let fill = ExecutionFill {
                            fill_id: *next_fill_id,
                            symbol: order.symbol.clone(),
                            maker_order_id: maker.order_id,
                            maker_user_id: maker.user_id,
                            taker_order_id: order.order_id,
                            taker_user_id: order.user_id,
                            side: OrderSide::Buy,
                            qty: match_qty,
                            price: fill_price,
                            timestamp_ns,
                        };
                        *next_fill_id += 1;

                        maker.qty -= match_qty;
                        let maker_empty = maker.qty == 0;
                        if maker_empty {
                            queue.pop_front();
                        }
                        (queue.is_empty(), fill)
                    };

                    if is_queue_empty {
                        book.asks_mut().remove(&lowest_ask_price);
                    }

                    unfilled_qty -= fill.qty;
                    let _ = order.record_fill(fill.qty, fill.price);
                    fills.push(fill);
                }

                // If remaining unfilled and this is a resting limit order, add to bids
                if unfilled_qty > 0 {
                    if let Some(limit) = limit_price {
                        book.add_limit_order(
                            OrderSide::Buy,
                            order.order_id,
                            order.user_id,
                            unfilled_qty,
                            limit,
                            timestamp_ns,
                        );
                    }
                }
            }
            OrderSide::Sell => {
                // Taker is SELLER -> matches against BIDS (highest price first)
                while unfilled_qty > 0 {
                    let highest_bid_price = match book.bids_mut().keys().next_back().copied() {
                        Some(p) => p,
                        None => break, // Book exhausted
                    };

                    // Guard: If limit sell, stop if best bid is below limit price
                    if let Some(limit) = limit_price {
                        if highest_bid_price < limit {
                            break;
                        }
                    }

                    // Match against front maker in queue at highest bid price
                    let (is_queue_empty, fill) = {
                        let queue = book.bids_mut().get_mut(&highest_bid_price).unwrap();
                        let maker = queue.front_mut().unwrap();
                        let match_qty = std::cmp::min(unfilled_qty, maker.qty);

                        // Calculate execution price with simulated slippage on market orders
                        let fill_price = if is_market && slippage_bps > 0 {
                            let slip_amount = BasisPoints(slippage_bps).apply_to(highest_bid_price);
                            normalize_to_tick(
                                highest_bid_price - slip_amount,
                                NSE_DEFAULT_TICK_SIZE_PAISE,
                            )
                        } else {
                            highest_bid_price
                        };

                        let fill = ExecutionFill {
                            fill_id: *next_fill_id,
                            symbol: order.symbol.clone(),
                            maker_order_id: maker.order_id,
                            maker_user_id: maker.user_id,
                            taker_order_id: order.order_id,
                            taker_user_id: order.user_id,
                            side: OrderSide::Sell,
                            qty: match_qty,
                            price: fill_price,
                            timestamp_ns,
                        };
                        *next_fill_id += 1;

                        maker.qty -= match_qty;
                        let maker_empty = maker.qty == 0;
                        if maker_empty {
                            queue.pop_front();
                        }
                        (queue.is_empty(), fill)
                    };

                    if is_queue_empty {
                        book.bids_mut().remove(&highest_bid_price);
                    }

                    unfilled_qty -= fill.qty;
                    let _ = order.record_fill(fill.qty, fill.price);
                    fills.push(fill);
                }

                // If remaining unfilled and this is a resting limit order, add to asks
                if unfilled_qty > 0 {
                    if let Some(limit) = limit_price {
                        book.add_limit_order(
                            OrderSide::Sell,
                            order.order_id,
                            order.user_id,
                            unfilled_qty,
                            limit,
                            timestamp_ns,
                        );
                    }
                }
            }
        }

        MatchResult {
            order_id: order.order_id,
            status: order.status.clone(),
            filled_qty: order.filled_qty,
            remaining_qty: order.qty - order.filled_qty,
            fills,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::account::AccountId;

    fn make_test_order(
        order_id: u64,
        user_id: u64,
        side: OrderSide,
        order_type: OrderType,
        qty: u32,
    ) -> Order {
        Order::new(
            OrderId(order_id),
            UserId(user_id),
            AccountId(1),
            "RELIANCE.NS",
            side,
            order_type,
            qty,
        )
        .unwrap()
    }

    #[test]
    fn test_market_buy_full_fill_single_maker() {
        let mut engine = MatchingEngine::new();
        let book = engine.get_or_create_book("RELIANCE.NS");

        // Resting Ask: 100 shares at Rs 2,500.00
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(10),
            UserId(99),
            100,
            Money::from_rupees(2500.0),
            1000,
        );

        let mut buy_order = make_test_order(1, 42, OrderSide::Buy, OrderType::Market, 40);
        let result = engine.match_order(&mut buy_order, 2000);

        assert_eq!(result.fills.len(), 1);
        assert_eq!(result.filled_qty, 40);
        assert_eq!(result.remaining_qty, 0);
        assert_eq!(result.fills[0].price, Money::from_rupees(2500.0));
        assert_eq!(result.fills[0].maker_user_id, UserId(99));
        assert_eq!(result.fills[0].taker_user_id, UserId(42));

        // Order book should now have 60 shares remaining at Rs 2,500.00
        let book = engine.get_book("RELIANCE.NS").unwrap();
        assert_eq!(book.best_ask(), Some((Money::from_rupees(2500.0), 60)));
    }

    #[test]
    fn test_market_buy_sweeping_multiple_price_levels() {
        let mut engine = MatchingEngine::new();
        let book = engine.get_or_create_book("RELIANCE.NS");

        // 10 shares @ Rs 2500, 20 shares @ Rs 2505, 30 shares @ Rs 2510
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(10),
            UserId(91),
            10,
            Money::from_rupees(2500.0),
            1000,
        );
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(11),
            UserId(92),
            20,
            Money::from_rupees(2505.0),
            1001,
        );
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(12),
            UserId(93),
            30,
            Money::from_rupees(2510.0),
            1002,
        );

        // Buy 25 shares (sweeps 10 @ 2500 + 15 @ 2505)
        let mut buy_order = make_test_order(1, 42, OrderSide::Buy, OrderType::Market, 25);
        let result = engine.match_order(&mut buy_order, 2000);

        assert_eq!(result.fills.len(), 2);
        assert_eq!(result.fills[0].qty, 10);
        assert_eq!(result.fills[0].price, Money::from_rupees(2500.0));
        assert_eq!(result.fills[1].qty, 15);
        assert_eq!(result.fills[1].price, Money::from_rupees(2505.0));

        // Remaining ask at Rs 2505 should be 5 shares
        let book = engine.get_book("RELIANCE.NS").unwrap();
        assert_eq!(book.best_ask(), Some((Money::from_rupees(2505.0), 5)));
        assert_eq!(book.total_ask_volume(), 35); // 5 @ 2505 + 30 @ 2510
    }

    #[test]
    fn test_limit_order_crossing_then_resting_remainder() {
        let mut engine = MatchingEngine::new();
        let book = engine.get_or_create_book("RELIANCE.NS");

        // 10 shares @ Rs 2500.00
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(10),
            UserId(91),
            10,
            Money::from_rupees(2500.0),
            1000,
        );

        // Limit buy 25 shares @ Rs 2500.00
        let mut buy_order = make_test_order(
            1,
            42,
            OrderSide::Buy,
            OrderType::Limit {
                limit_price: Money::from_rupees(2500.0),
            },
            25,
        );
        let result = engine.match_order(&mut buy_order, 2000);

        // 10 filled, 15 remainder rests on bid side
        assert_eq!(result.filled_qty, 10);
        assert_eq!(result.remaining_qty, 15);
        assert_eq!(result.fills.len(), 1);

        let book = engine.get_book("RELIANCE.NS").unwrap();
        // Asks are now empty
        assert_eq!(book.best_ask(), None);
        // Best bid is now the 15 resting shares @ Rs 2500.00
        assert_eq!(book.best_bid(), Some((Money::from_rupees(2500.0), 15)));
    }

    #[test]
    fn test_non_crossing_limit_order_directly_rests() {
        let mut engine = MatchingEngine::new();
        let book = engine.get_or_create_book("RELIANCE.NS");

        // Best ask is Rs 2500.00
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(10),
            UserId(91),
            10,
            Money::from_rupees(2500.0),
            1000,
        );

        // Limit buy at Rs 2490.00 (below ask)
        let mut buy_order = make_test_order(
            1,
            42,
            OrderSide::Buy,
            OrderType::Limit {
                limit_price: Money::from_rupees(2490.0),
            },
            15,
        );
        let result = engine.match_order(&mut buy_order, 2000);

        assert_eq!(result.fills.len(), 0);
        assert_eq!(result.filled_qty, 0);
        assert_eq!(result.remaining_qty, 15);
        assert_eq!(result.status, OrderStatus::Submitted);

        let book = engine.get_book("RELIANCE.NS").unwrap();
        assert_eq!(book.best_bid(), Some((Money::from_rupees(2490.0), 15)));
        assert_eq!(book.best_ask(), Some((Money::from_rupees(2500.0), 10)));
        assert_eq!(book.spread(), Some(Money::from_rupees(10.0)));
    }

    #[test]
    fn test_market_sell_sweeping_bids() {
        let mut engine = MatchingEngine::new();
        let book = engine.get_or_create_book("RELIANCE.NS");

        // Resting bids: 10 @ 2500.00, 15 @ 2495.00
        book.add_limit_order(
            OrderSide::Buy,
            OrderId(10),
            UserId(81),
            10,
            Money::from_rupees(2500.0),
            1000,
        );
        book.add_limit_order(
            OrderSide::Buy,
            OrderId(11),
            UserId(82),
            15,
            Money::from_rupees(2495.0),
            1001,
        );

        // Market sell 20 shares (10 @ 2500 + 10 @ 2495)
        let mut sell_order = make_test_order(2, 42, OrderSide::Sell, OrderType::Market, 20);
        let result = engine.match_order(&mut sell_order, 2000);

        assert_eq!(result.fills.len(), 2);
        assert_eq!(result.fills[0].qty, 10);
        assert_eq!(result.fills[0].price, Money::from_rupees(2500.0));
        assert_eq!(result.fills[1].qty, 10);
        assert_eq!(result.fills[1].price, Money::from_rupees(2495.0));

        let book = engine.get_book("RELIANCE.NS").unwrap();
        assert_eq!(book.best_bid(), Some((Money::from_rupees(2495.0), 5)));
    }

    #[test]
    fn test_simulated_slippage_on_market_order() {
        // Engine with 5 BPS slippage (0.05%)
        let mut engine = MatchingEngine::with_slippage(5);
        let book = engine.get_or_create_book("RELIANCE.NS");

        book.add_limit_order(
            OrderSide::Sell,
            OrderId(10),
            UserId(91),
            10,
            Money::from_rupees(2000.0),
            1000,
        );

        // 5 BPS on Rs 2,000 = Rs 1.00 slippage -> fill at Rs 2,001.00
        let mut buy_order = make_test_order(1, 42, OrderSide::Buy, OrderType::Market, 10);
        let result = engine.match_order(&mut buy_order, 2000);

        assert_eq!(result.fills.len(), 1);
        assert_eq!(result.fills[0].price, Money::from_rupees(2001.0));
    }

    #[test]
    fn test_market_order_liquidity_exhaustion() {
        let mut engine = MatchingEngine::new();
        let book = engine.get_or_create_book("RELIANCE.NS");

        // Only 10 shares available
        book.add_limit_order(
            OrderSide::Sell,
            OrderId(10),
            UserId(91),
            10,
            Money::from_rupees(2500.0),
            1000,
        );

        // Market order asks for 25 shares
        let mut buy_order = make_test_order(1, 42, OrderSide::Buy, OrderType::Market, 25);
        let result = engine.match_order(&mut buy_order, 2000);

        assert_eq!(result.filled_qty, 10);
        assert_eq!(result.remaining_qty, 15);
        // Market order does NOT rest on book, remains partially filled
        let book = engine.get_book("RELIANCE.NS").unwrap();
        assert_eq!(book.best_ask(), None);
        assert_eq!(book.best_bid(), None);
    }
}
